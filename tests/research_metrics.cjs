const assert = require('node:assert/strict');
const Metrics = require('../deblock/web/research-metrics.js');
const m = new Metrics();
m.edit(0);
m.edit(100, 2);
m.edit(200);
m.edit(300, 1);
m.words(1, 400);
m.edit(6000, 1);
m.words(1, 6200);
m.words(1, 6400);
const summary = m.summary(6500, 2);
assert.deepEqual(m.events.correction_ms, [100, 6000]);
assert.equal(summary.deleted_chars, 4);
assert.equal(summary.corrections_per_word, 2/3);
assert.equal(summary.active_ms, 5800);
assert.equal(summary.pauses, 1);
assert.deepEqual(m.events.pause_durations_ms, [5600]);
assert.equal(summary.first_word_ms, 400);
assert.equal(summary.longest_pause_ms, 5600);
assert.equal(summary.mean_interval_ms, 3000);
assert.equal(summary.median_interval_ms, 3000);
m.pause();
m.edit(15000);
assert.equal(m.summary(15000, 2).pauses, 1);
